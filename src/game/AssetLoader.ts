import type { BoatKind } from './config'
import { NATIVE_FAMILIES, PALETTE, type ColorDef } from './Palette'
import { makeTintSource, recolorBuilding, recolorImage, tintedSheet, type Img, type Sheet } from './Sprites'
import type { BoatDir } from './types'
import { frameCount } from './SpriteAnimator'
import { ART_V } from './artVersion'

export type { Img, Sheet }

const BASE = `${import.meta.env.BASE_URL}assets/ts/`
const SHIPS = `${import.meta.env.BASE_URL}assets/ships/`
const KNIGHT = `${import.meta.env.BASE_URL}assets/knight/`
const PROPS = `${import.meta.env.BASE_URL}assets/props/`
const url = (p: string) => BASE + p.split('/').map(encodeURIComponent).join('/')

/**
 * Frame widths are the only per-sheet constants. Heights and frame counts come from the loaded image dimensions:
 *   Water Foam.png 3072×192 → 16 frames of 192; Warrior/Pawn sheets are 192-high strips of 192-wide frames;
 *   Tree1/2 are 1536×256 (8 × 192×256), Tree3/4 1536×192 (8 × 192×192); Bushes 1024×128 (8 × 128).
 */
const FRAME_W: Record<string, number> = { foam: 192, tree: 192, bush: 128, unit: 192, lancer: 320 }

export type Assets = {
  tileset: HTMLImageElement
  water: HTMLImageElement
  foam: Sheet
  trees: Sheet[]
  stumps: Img[]
  bushes: Sheet[]
  rocks: Img[]
  houses: Img[]
  monasteries: Img[] // level 2 towns
  barracks: Img[]
  lots: Img[]
  towers: Img[]
  arrow: HTMLImageElement
  archer: Record<string, Sheet>[] // [colorIdx][Idle|Run|Shoot]
  lancer: Record<string, Sheet>[] // [colorIdx][Idle|Run|Defence|AtkRight|AtkDown|AtkUp|AtkDownRight|AtkUpRight]
  warrior: Record<string, Sheet>[] // [colorIdx][Idle|Run|Attack1|Attack2|Guard]
  knight: { Run: Sheet; Idle: Sheet; Attack: Sheet }[] // [colorIdx]: the artist's 6-frame gallop, 8-frame idle and 12-frame lance attack (scripts/make-knight.py). Recoloured like the ships (its blues sit at the same hue)
  pawn: Record<string, Sheet>[] // [colorIdx][Idle|Run|Chop|IdleWood|RunWood]
  ships: Record<BoatKind, Record<BoatDir, Img>[]>
  bargeOpen: Record<BoatDir, Img>[] // the barge with its bow ramp lowered (drawn offset by BARGE_OPEN_OFFSET so the two hulls coincide) // [kind][colorIdx][direction], generated by scripts/make-ships.py
  fx: { explosion: Sheet; explosion2: Sheet; splash: Sheet; fire: Sheet; dust1: Sheet; dust2: Sheet; wake1: Sheet; wake2: Sheet; wakeSplash: Sheet }
  ui: Record<string, HTMLImageElement>
  woodResource: HTMLImageElement
  gold: HTMLImageElement[] // gold stones 1..6 (index 0 = stone 1)
  sheep: { idle: Sheep; move: Sheep }
  props: { pillar: HTMLImageElement; statue: HTMLImageElement; crate: HTMLImageElement; yard: HTMLImageElement }
  meat: HTMLImageElement
}
type Sheep = Sheet

const loadImage = (src: string) => new Promise<HTMLImageElement>((res, rej) => { const i = new Image(); i.onload = () => res(i); i.onerror = () => rej(new Error('Failed to load ' + src)); i.src = src })
/** A copy of a sprite washed toward a colour (the foam of a wake is tinted to sit in the water instead of glaring white on it). */
const tinted = (img: Img, rgba: string): HTMLCanvasElement => {
  const c = document.createElement('canvas'); c.width = img.width; c.height = img.height
  const g = c.getContext('2d')!; g.drawImage(img, 0, 0); g.globalCompositeOperation = 'source-atop'; g.fillStyle = rgba; g.fillRect(0, 0, c.width, c.height)
  return c
}
const WATER_WASH = 'rgba(70,160,166,0.66)' // (the sea's own teal)
const sheet = (img: Img, fw: number): Sheet => ({ img, fw, fh: img.height, frames: frameCount(img.width, fw) })

export async function loadAssets(): Promise<Assets> {
  const L = (p: string) => loadImage(url(p))
  const colors = NATIVE_FAMILIES // the five real sprite families; every other kingdom colour is recoloured from Blue
  const [tileset, water, foamImg, woodResource] = await Promise.all([L('Terrain/Tileset/Tilemap_color1.png'), L('Terrain/Tileset/Water Background color.png'), L('Terrain/Tileset/Water Foam.png'), L('Terrain/Resources/Wood/Wood Resource/Wood Resource.png')])
  const idx = [1, 2, 3, 4]
  const [treeImgs, stumps, bushImgs, rocks] = await Promise.all([
    Promise.all(idx.map(i => L(`Terrain/Resources/Wood/Trees/Tree${i}.png`))),
    Promise.all(idx.map(i => L(`Terrain/Resources/Wood/Trees/Stump ${i}.png`))),
    Promise.all(idx.map(i => L(`Terrain/Decorations/Bushes/Bushe${i}.png`))),
    Promise.all(idx.map(i => L(`Terrain/Decorations/Rocks/Rock${i}.png`))),
  ])
  const [houses, lots, barracks, towers, monasteries] = await Promise.all(['House1', 'House3', 'Barracks', 'Tower', 'Monastery'].map(b => Promise.all(colors.map(c => L(`Buildings/${c} Buildings/${b}.png`)))))
  const arrow = await L('Units/Blue Units/Archer/Arrow.png')
  const [knightRun, knightIdle, knightAttack] = await Promise.all(['Run', 'Idle', 'Attack'].map(n => loadImage(`${KNIGHT}Knight_${n}.png?v=${ART_V}`)))
  const archer = await Promise.all(colors.map(async c => {
    const names = ['Idle', 'Run', 'Shoot']
    const imgs = await Promise.all(names.map(n => L(`Units/${c} Units/Archer/Archer_${n}.png`)))
    return Object.fromEntries(names.map((n, i) => [n, sheet(imgs[i], FRAME_W.unit)]))
  }))
  const lancer = await Promise.all(colors.map(async c => {
    const files: [string, string][] = [['Idle', 'Idle'], ['Run', 'Run'], ['Defence', 'Right_Defence'], ['AtkRight', 'Right_Attack'], ['AtkDown', 'Down_Attack'], ['AtkUp', 'Up_Attack'], ['AtkDownRight', 'DownRight_Attack'], ['AtkUpRight', 'UpRight_Attack']]
    const imgs = await Promise.all(files.map(([, f]) => L(`Units/${c} Units/Lancer/Lancer_${f}.png`)))
    return Object.fromEntries(files.map(([n], i) => [n, sheet(imgs[i], FRAME_W.lancer)]))
  }))
  const warrior = await Promise.all(colors.map(async c => {
    const names = ['Idle', 'Run', 'Attack1', 'Attack2', 'Guard']
    const imgs = await Promise.all(names.map(n => L(`Units/${c} Units/Warrior/Warrior_${n}.png`)))
    return Object.fromEntries(names.map((n, i) => [n, sheet(imgs[i], FRAME_W.unit)]))
  }))
  const pawn = await Promise.all(colors.map(async c => {
    const files: [string, string][] = [['Idle', 'Pawn_Idle'], ['Run', 'Pawn_Run'], ['Chop', 'Pawn_Interact Axe'], ['Build', 'Pawn_Interact Hammer'], ['IdleWood', 'Pawn_Idle Wood'], ['RunWood', 'Pawn_Run Wood'], ['IdleMeat', 'Pawn_Idle Meat'], ['RunMeat', 'Pawn_Run Meat'], ['IdleGold', 'Pawn_Idle Gold'], ['RunGold', 'Pawn_Run Gold']]
    const imgs = await Promise.all(files.map(([, f]) => L(`Units/${c} Units/Pawn/${f}.png`)))
    return Object.fromEntries(files.map(([n], i) => [n, sheet(imgs[i], FRAME_W.unit)]))
  }))
  const dirs: BoatDir[] = ['up', 'down', 'left', 'right']
  const shipBase = async (kind: BoatKind | 'bargeopen') => Object.fromEntries(await Promise.all(dirs.map(async d => [d, await loadImage(`${SHIPS}${kind}_${d}.png?v=${ART_V}`)] as const))) as Record<BoatDir, Img>
  const [shipBoat, shipZum, shipCargo, shipGun, shipBarge, shipBargeOpen, exp1, exp2, splash, fire, dust1, dust2] = await Promise.all([shipBase('boat'), shipBase('zumwalt'), shipBase('cargo'), shipBase('gunship'), shipBase('barge'), shipBase('bargeopen'), L('Particle FX/Explosion_01.png'), L('Particle FX/Explosion_02.png'), L('Particle FX/Water Splash.png'), L('Particle FX/Fire_03.png'), L('Particle FX/Dust_01.png'), L('Particle FX/Dust_02.png')])
  const [goldStones, sheepIdle, sheepMove, meat, pillar, statue, crate, yard] = await Promise.all([
    Promise.all([1, 2, 3, 4, 5, 6].map(i => L(`Terrain/Resources/Gold/Gold Stones/Gold Stone ${i}.png`))),
    L('Terrain/Resources/Meat/Sheep/Sheep_Idle.png'), L('Terrain/Resources/Meat/Sheep/Sheep_Move.png'), L('Terrain/Resources/Meat/Meat Resource/Meat Resource.png'),
    loadImage(`${PROPS}pillar.png?v=${ART_V}`), loadImage(`${PROPS}statue.png?v=${ART_V}`), loadImage(`${PROPS}crate.png?v=${ART_V}`), loadImage(`${PROPS}yard.png?v=${ART_V}`),
  ])
  const uiFiles: Record<string, string> = {
    roundBlue: 'Buttons/SmallBlueRoundButton_Regular.png', roundBluePressed: 'Buttons/SmallBlueRoundButton_Pressed.png',
    roundRed: 'Buttons/SmallRedRoundButton_Regular.png', roundRedPressed: 'Buttons/SmallRedRoundButton_Pressed.png',
    iconShield: 'Icons/Icon_06.png', iconLog: 'Icons/Icon_02.png', iconSwords: 'Icons/Icon_05.png',
  }
  const uiEntries = await Promise.all(Object.entries(uiFiles).map(async ([k, f]) => [k, await L(`UI Elements/UI Elements/${f}`)] as const))
  // ---- one entry per palette colour: native colours use the real sheets, the others recolour the Blue ones on demand ----
  const blueIdx = NATIVE_FAMILIES.indexOf('Blue')
  const strips = (fams: Record<string, Sheet>[]): Record<string, Sheet>[] => {
    const keys = Object.keys(fams[0])
    const srcs = Object.fromEntries(keys.map(k => [k, makeTintSource(fams.map(f => f[k]))]))
    return PALETTE.map(c => c.native ? fams[NATIVE_FAMILIES.indexOf(c.native)] : Object.fromEntries(keys.map(k => [k, tintedSheet(srcs[k], c)])))
  }
  const buildings = (fams: Img[]): Img[] => PALETTE.map(c => (c.native ? fams[NATIVE_FAMILIES.indexOf(c.native)] : recolorBuilding(fams[blueIdx], fams, c)))
  const ships = (base: Record<BoatDir, Img>, squash?: { center: number; k: number }): Record<BoatDir, Img>[] => PALETTE.map(c => { const sp = shipSpec(c); return Object.fromEntries(dirs.map(d => [d, sp ? recolorImage(base[d], sp, isShipTeam, squash) : base[d]])) as Record<BoatDir, Img> })
  const WIDE_HULL = { center: 218, k: 0.3 } // the Zumwalt and barge art mix teal, blue and navy: squeeze them toward one hue before recolouring
  return {
    tileset, water, foam: sheet(foamImg, FRAME_W.foam), woodResource,
    trees: treeImgs.map(i => sheet(i, FRAME_W.tree)), stumps, bushes: bushImgs.map(i => sheet(i, FRAME_W.bush)), rocks,
    houses: buildings(houses), monasteries: buildings(monasteries), lots: buildings(lots), barracks: buildings(barracks), towers: buildings(towers), arrow,
    archer: strips(archer), lancer: strips(lancer), warrior: strips(warrior), pawn: strips(pawn),
    knight: PALETTE.map(c => { const sp = shipSpec(c), tint = (im: Img) => (sp ? recolorImage(im, sp, isShipTeam) : im); return { Run: sheet(tint(knightRun), 192), Idle: sheet(tint(knightIdle), 192), Attack: sheet(tint(knightAttack), 192) } }),
    ships: { boat: ships(shipBoat), zumwalt: ships(shipZum, WIDE_HULL), cargo: ships(shipCargo), gunship: ships(shipGun), barge: ships(shipBarge, WIDE_HULL) },
    bargeOpen: ships(shipBargeOpen, WIDE_HULL),
    gold: goldStones, sheep: { idle: sheet(sheepIdle, 128), move: sheet(sheepMove, 128) }, meat, props: { pillar, statue, crate, yard }, fx: { explosion: sheet(exp1, 192), explosion2: sheet(exp2, 192), splash: sheet(splash, 192), fire: sheet(fire, 64), dust1: sheet(dust1, 64), dust2: sheet(dust2, 64), wake1: sheet(tinted(dust1, WATER_WASH), 64), wake2: sheet(tinted(dust2, WATER_WASH), 64), wakeSplash: sheet(tinted(splash, WATER_WASH), 192) },
    ui: Object.fromEntries(uiEntries),
  }
}

/** The ship sprites are a deeper blue (hue ≈ 218°) than the unit sprites (≈ 185°), so their shift is smaller by the difference. */
const SHIP_HUE_OFFSET = 33
const NATIVE_SHIP: Record<string, ColorDef | null> = {
  Blue: null, Purple: { name: 'Purple', hex: '', shift: 57 }, Red: { name: 'Red', hex: '', shift: -214, sat: 1.1 },
  Yellow: { name: 'Yellow', hex: '', shift: -170, sat: 1.05, light: 1.08 }, Black: { name: 'Black', hex: '', sat: 0.08, light: 0.6 },
}
const shipSpec = (c: ColorDef): ColorDef | null => (c.native ? NATIVE_SHIP[c.native] : { ...c, shift: (c.shift ?? 0) - SHIP_HUE_OFFSET })
const isShipTeam = (r: number, g: number, b: number) => {
  const mx = Math.max(r, g, b), mn = Math.min(r, g, b)
  if (mx === mn) return false
  const d = mx - mn, h = ((mx === r ? ((g - b) / d) % 6 : mx === g ? (b - r) / d + 2 : (r - g) / d + 4) * 60 + 360) % 360
  return h >= 155 && h <= 260 && d / mx > 0.22 // (the teal Zumwalt's stone reaches down to ~160°)
}
